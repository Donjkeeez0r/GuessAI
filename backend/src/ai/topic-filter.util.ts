/**
 * Тема приходит от пользователя и коротка, поэтому склеиваем её в одну строку:
 * так «н а р к о т и к» тоже ловится.
 */
export function validateTopic(topic: string): boolean {
  const cleanTopic = topic.toLowerCase().replace(/[^a-z0-9а-яё]/g, '');

  if (
    BLOCKED_WORDS.some((word) => cleanTopic.includes(word.replaceAll(' ', '')))
  ) {
    throw new BadRequestException('Эта тема запрещена для генерации пака');
  }

  return true;
}

/**
 * Модерация длинного текста (сгенерированные вопросы и варианты ответов)
 * по тому же стоп-листу. В отличие от `validateTopic` пробелы сохраняются:
 * иначе безобидное «несу картину» склеилось бы в запрещённую подстроку.
 * Составные записи стоп-листа дополнительно проверяются по склейке.
 */
export function containsBlockedWords(text: string): boolean {
  const normalized = text
    .toLowerCase()
    .replace(/[^a-z0-9а-яё]+/g, ' ')
    .trim();
  const collapsed = normalized.replaceAll(' ', '');

  return BLOCKED_WORDS.some((word) => {
    const lowered = word.toLowerCase();

    if (normalized.includes(lowered)) return true;

    return (
      lowered.includes(' ') && collapsed.includes(lowered.replaceAll(' ', ''))
    );
  });
}
